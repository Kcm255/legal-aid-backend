def get_summary_prompt(extracted_text: str, context_chunks: list[str], language: str) -> str:
    language_names = {
        "en": "English",
        "hi": "Hindi",
        "mr": "Marathi",
    }

    lang_name = language_names.get(language, "English")

    # Keep only a few retrieved chunks
    if context_chunks:
        context_str = "\n\n---\n\n".join(context_chunks[:3])
    else:
        context_str = "No additional legal context."

    # Prevent huge prompts
    document_text = extracted_text[:4000]

    return f"""
You are an expert Indian Legal Aid Assistant.

Your task is to explain the legal document in SIMPLE {lang_name}.

MANDATORY LANGUAGE RULE:
- Every user-facing value must be written in {lang_name}.
- For Hindi or Marathi, do not write the summary values in English.
- Translate the document type, summary sentences, action steps, and labels.
- Keep proper names, dates, amounts, and legal section names accurate.

Use ONLY the information present in:

1. The uploaded document.
2. The retrieved legal context.

Never invent facts.

=====================
LEGAL CONTEXT
=====================

{context_str}

=====================
DOCUMENT
=====================

{document_text}

=====================
IMPORTANT RULES
=====================

Return ONLY valid JSON.

Do NOT write markdown.

Do NOT write explanations.

Do NOT use ```.

If information is missing use:
"" for strings
[] for arrays

JSON FORMAT

{{
    "document_type": "",

    "summary": {{
        "what_it_is": "",
        "what_it_means": "",
        "what_to_do": ""
    }},

    "urgency": "low|medium|high",

    "key_parties": [],

    "extracted_dates": [
        {{"label": "Date of Hearing", "value": "DD/MM/YYYY"}}
    ],

    "extracted_amounts": [
        {{"label": "Outstanding Amount", "value": "Rs. X"}}
    ],

    "legal_sections_referenced": []
}}

LIMITS

- what_it_is : maximum 2 sentences
- what_it_means : maximum 3 sentences
- what_to_do : maximum 4 numbered points
- maximum 5 parties
- maximum 5 dates
- maximum 5 amounts
- maximum 5 legal sections

DATE LABEL EXAMPLES (use the most appropriate specific label):
Date of Issue, Date of Hearing, Date of Summons, Deadline to Respond, Date of Commencement,
Date of Expiry, Date of Execution, Last Date for Payment, Date of Registration, Court Date,
Notice Period Ends, Date of Enforcement, Date of Filing

AMOUNT LABEL EXAMPLES (use the most appropriate specific label):
Principal Amount, Outstanding Loan, Monthly EMI, Penalty Charges, Court Fee,
Interest Due, Total Dues, Fine Amount, Stamp Duty, Legal Charges, Security Deposit,
Mortgage Amount, Compensation Amount

AMOUNT EXTRACTION RULES:
- Extract only values that contain a numeric amount. Never return entries such as "Rs." or "Amount" without digits.
- Never use the generic label "Amount". Describe what the amount is for, such as Repair Amount,
  Rent Amount, Principal Amount, Outstanding Amount, Penalty Charges, or Total Dues.
- If the document does not state what an amount is for, use "Document Amount".
- Do not treat counts, dates, years, percentages, vacancy numbers, or business figures as monetary
  amounts unless they are explicitly preceded or followed by a currency marker or a money-related term.

Return ONLY the JSON object.
"""


def get_translation_prompt(summary_json: dict, target_language: str) -> str:
    language_names = {
        "en": "English",
        "hi": "Hindi",
        "mr": "Marathi",
    }

    lang_name = language_names.get(target_language, "English")

    script_rule = (
        "Use Devanagari script for Hindi. Do not copy English sentences."
        if target_language == "hi"
        else "Use Devanagari script for Marathi. Do not copy English sentences."
        if target_language == "mr"
        else ""
    )

    return f"""
Translate the following JSON into {lang_name}.

Translate ONLY the values.

This is a mandatory translation. Every human-readable value must be in {lang_name}.
Do not leave English sentences in the output when the target language is Hindi or Marathi.
{script_rule}
Return translated sentences, not transliterations or the original English text.

Do NOT translate the JSON keys.

Do NOT change the JSON structure.

Input:

{summary_json}

Return ONLY valid JSON.
"""


def get_audio_prompt(summary_json: dict, target_language: str) -> str:
    """Create a short, natural spoken explanation of the structured summary."""
    language_names = {
        "en": "English",
        "hi": "Hindi",
        "mr": "Marathi",
    }
    lang_name = language_names.get(target_language, "English")
    return f"""
You are preparing an audio narration for a rural legal-aid user.

Rewrite the summary below as one clear, natural spoken explanation in {lang_name}.
The narration must be entirely in {lang_name}; do not use English headings, labels,
or filler words. Keep proper names, dates, amounts, and legal section names accurate.
Explain what the document is about, what it means for the person, and the most
important next step. Do not mechanically read every field, list, party, date, or
amount. Do not mention that you are rewriting JSON. Keep it to 80-140 words and
return only the narration as plain text, with no markdown or bullet points.

SUMMARY JSON:
{summary_json}
"""


def get_followup_prompt(
    question: str,
    context_chunks: list[str],
    original_text: str,
    chat_history: list[dict],
    language: str,
) -> str:

    language_names = {
        "en": "English",
        "hi": "Hindi",
        "mr": "Marathi",
    }

    lang_name = language_names.get(language, "English")

    if context_chunks:
        context_str = "\n\n---\n\n".join(context_chunks[:3])
    else:
        context_str = "No additional context."

    history = ""

    for msg in chat_history[-6:]:
        role = "User" if msg["role"] == "user" else "Assistant"
        history += f"{role}: {msg['message']}\n"

    return f"""
You are an Indian Legal Aid Assistant.

Answer ONLY using:

1. Uploaded document
2. Retrieved legal context

Do not invent legal facts.

Language: {lang_name}

MANDATORY LANGUAGE RULE:
- Write the entire answer in {lang_name}.
- Do not answer in English when the requested language is Hindi or Marathi.
- Translate headings, labels, explanations, and action steps too. Keep only proper
  names, document titles, legal section names, and unavoidable abbreviations unchanged.

=====================
LEGAL CONTEXT
=====================

{context_str}

=====================
DOCUMENT
=====================

{original_text[:3000]}

=====================
CHAT HISTORY
=====================

{history}

=====================
QUESTION
=====================

{question}

Keep the answer under 300 words.

Format your response clearly using:
- **Bold** for important labels, party names, amounts, or dates (e.g., **Rent:** Rs. 32,000/-)
- Numbered lists (1. 2. 3.) for steps or multiple points
- Bullet points (- ) for grouped facts
- Short section headings ending with a colon if the answer has multiple parts

Do NOT write a wall of text. Structure the answer so it is easy to scan at a glance.
"""
